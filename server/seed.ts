export function buildSeedWatches(): Watch[] {
  return seedWatches.map((w, i) => {
    const { image, days, ...rest } = w;
    const slugBase = `${rest.brand}-${rest.name}`
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');
    return {
      ...rest,
      id: `w_${String(i + 1).padStart(4, '0')}`,
      slug: slugBase,
      images: rest.images.length ? rest.images : [image],
      views: 20 + ((i * 37) % 180),
      sortOrder: i,
      createdAt: daysAgo(days),
      updatedAt: daysAgo(days),
    };
  });
}
